import re
import sys

import pslib

# docs/routing_guide.md: every net that is not fully connected, grouped in routing order, with its
# terminals and the rules that apply. connectivity comes from the copper itself (not the drc report,
# which stops at 499 items). usage: routeguide.py <board> <out.md>
PCB, OUT = sys.argv[1], sys.argv[2]
r = pslib.Router(PCB, [])
terms = {}
for (x, y, hx, hy, n, lays, rnd, p) in r.bd.pads:
    if n and not n.startswith('unconnected'):
        terms.setdefault(n, []).append((p.GetParentFootprint().GetReference() + ':' + p.GetNumber(), (x, y), lays, (hx, hy)))
zs = r.bd.b.Zones()
planes = {zs[i].GetNetname() for i in range(len(zs))} | {'GND'}
GROUPS = [
    ('DDR3', r'^DDR_', 'see [DDR3 routing](ddr_routing.md): byte lanes within 1.4 mm of their DQS, address/command '
                      'within 3 mm of CK, pairs within 0.15 mm, 2-3 vias per net'),
    ('STM32 FMC and FPGA config', r'^(FMC_|FPGA_)', '125 MHz, SE50 (0.127 mm outer, 0.23 mm inner), no length '
                                                    'matching; JTAG and config are slow'),
    ('QSPI', r'^QSPI_', 'up to 133 MHz: keep each net under about 25 mm and within 10 mm of QSPI_CLK; route CLK '
                        'first; SE50'),
    ('RMII and MDIO', r'^ETH_', '50 MHz: REF_CLK first and direct; data within about 30 mm of REF_CLK; SE50'),
    ('ULPI', r'^ULPI_', '60 MHz, PHY-sourced clock: CK first, all under about 50 mm, data within 10 mm of CK; SE50'),
    ('Ethernet MDI', r'^/MCU_IO/ETH_(TX|RX)', '100 ohm differential (DIFF100 class), P/N within 0.15 mm, keep '
                                              'away from the switchers; terminations R56-R59 at the PHY'),
    ('USB', r'^(USBH_|USBHS_|VBUS)', '90 ohm differential (USB90 class), P/N within 0.15 mm'),
    ('VITA LA and mezzanine clocks', r'^MEZZ_(LA|CLK)', '100 ohm differential (DIFF100), P/N within 0.15 mm; '
                                                       'through the 2.8 mm gap above the FPGA'),
    ('transceivers', r'^(GTP|SFP|MEZZ_DP|MEZZ_GBT|/FPGA_GTP)', 'routed and skew-matched; anything here is sideband'),
    ('PHY local', r'^/MCU_IO/(ETH|ULPI)', 'short local nets at the PHYs; crystals as short as possible'),
    ('power and enables', r'^(/POWER/|\+|-5V|PG_|VADJ|ETH_AVDD|ETH_VDDCR|VTT|VREF)', 'power nets at the width '
                                                                                   'their current needs'),
    ('everything else', r'.', 'low-speed: any layer, 0.127 mm'),
]
opens = []
for n, ts in sorted(terms.items()):
    if n in planes or len(ts) < 2:
        continue
    c = r.comp(n, ts)
    if len(set(c)) > 1:
        pieces = {}
        for t, k in zip(ts, c):
            pieces.setdefault(k, []).append(t[0])
        opens.append((n, sorted(pieces.values(), key=len, reverse=True)))
used = set()
out = ['# routing guide: open nets', '',
       'Generated by `gen/routeguide.py` from the board copper. A net is listed when its pads are not all joined; '
       'each line shows the separate pieces (pads already joined to each other share a piece).', '',
       'Order follows the suggested routing order. %d nets open in total.' % len(opens), '']
for title, rx, rule in GROUPS:
    sel = [(n, p) for n, p in opens if re.search(rx, n) and n not in used]
    if not sel:
        continue
    used |= {n for n, _ in sel}
    out += ['## %s (%d open)' % (title, len(sel)), '', rule, '', '| net | pieces |', '|---|---|']
    for n, p in sel:
        out.append('| %s | %s |' % (n, ' / '.join(', '.join(x[:6]) + (' ...' if len(x) > 6 else '') for x in p)))
    out.append('')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote %s: %d open nets' % (OUT, len(opens)))
