import os
import re
import sys

import pcbnew

# FPGA pin constraints for Vivado from docs/pinout.md (bank tables: ball, pin function, net, VCCO) and the
# board (transceiver balls), with pin-planning checks. usage: xdcgen.py <board> <pinout.md> <out.xdc>
PCB, PINOUT, OUT = sys.argv[1:4]
txt = open(PINOUT).read()
rows = {}
for sec in re.finditer(r'^### bank (\d+) \(VCCO ([^)]+)\)\n(.*?)(?=^#)', txt, re.M | re.S):
    bank, vcco, body = sec.group(1), sec.group(2).strip(), sec.group(3)
    for m in re.finditer(r'^\| (\w+) \| ([\w]+) \| ([^ |]+) \|', body, re.M):
        ball, fn, net = m.groups()
        if ball in ('ball',) or set(ball) == {'-'}:
            continue
        rows[ball] = (bank, fn, net, vcco)
b = pcbnew.LoadBoard(PCB)
u = b.FindFootprintByReference('U100')
gtp = {}
for k in range(len(u.Pads())):
    p = u.Pads()[k]
    n = p.GetNetname()
    if n.startswith(('GTP', '/FPGA_GTP/REFCLK')):
        gtp[p.GetNumber()] = n


allnets = {r[2] for r in rows.values()} | set(gtp.values())
# a net is one half of a differential pair only if its partner exists (DDR_RAS_N etc. are active low)
isdiff = lambda n: (n.endswith('_P') and n[:-2] + '_N' in allnets) or (n.endswith('_N') and n[:-2] + '_P' in allnets)


def port(net):
    return re.sub(r'[^a-z0-9_]', '_', net.lower().strip('/').replace('/', '_'))


def iostd(bank, net, vcco):
    diff = isdiff(net)
    if vcco.startswith('3.3'):
        return 'LVCMOS33'
    if vcco.startswith('1.35'):
        return 'DIFF_SSTL135' if diff else 'SSTL135'
    if vcco == 'VADJ':
        return 'LVDS_25' if diff else 'LVCMOS25'
    return None


issues, notes = [], []
lines = ['# MAIN_COMPUTE_BOARD v1_r1: XC7A100T-2FGG484 pin constraints',
         '# generated by gen/xdcgen.py from docs/pinout.md and the board; do not edit by hand',
         '# VADJ banks (35, 16) assume VADJ = 2.5 V (LVDS_25 / LVCMOS25). at other VADJ settings change the',
         '# standards: HR banks only support LVDS_25 outputs at VCCO 2.5 V', '',
         'set_property CFGBVS VCCO [current_design]', 'set_property CONFIG_VOLTAGE 3.3 [current_design]',
         'set_property BITSTREAM.CONFIG.CONFIGRATE 50 [current_design]', '']
by_bank = {}
for ball, (bank, fn, net, vcco) in rows.items():
    by_bank.setdefault(bank, []).append((net, ball, fn, vcco))
for bank in sorted(by_bank, key=int):
    lst = sorted(by_bank[bank])
    lines.append('# bank %s, VCCO %s' % (bank, lst[0][3]))
    for net, ball, fn, vcco in lst:
        if net in ('NC', '') or net.startswith('unconnected'):
            continue
        s = iostd(bank, net, vcco)
        lines.append('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %-12s} [get_ports %s]' % (ball, s, port(net)))
        if net.startswith('MEZZ_') and net.endswith(('_M2C_P', '_M2C_N')) or (net.startswith('MEZZ_LA') and s == 'LVDS_25'):
            pass
    lines.append('')
# vadj lvds inputs: on-chip 100 R termination for card-to-carrier pairs
lines.append('# card-to-carrier clocks: internal differential termination')
for ball, (bank, fn, net, vcco) in rows.items():
    if vcco == 'VADJ' and net.endswith('_M2C_P'):
        lines.append('set_property DIFF_TERM TRUE [get_ports %s]' % port(net))
lines.append('')
lines.append('# transceivers (quad 216): location only, no IOSTANDARD on MGT pins')
for ball, net in sorted(gtp.items(), key=lambda x: x[1]):
    lines.append('set_property PACKAGE_PIN %-4s [get_ports %s]' % (ball, port(net)))
lines += ['', '# clocks',
          'create_clock -period 10.000 -name sysclk_100m [get_ports sysclk_100m]',
          'create_clock -period 8.000 -name fmc_clk [get_ports fmc_clk]',
          'create_clock -period 8.000 -name gtp_refclk0 [get_ports gtp_refclk0_p]',
          '# gtp_refclk1 (VITA GBTCLK0_M2C) and mezz_clk0/1_m2c depend on the card: add create_clock per card']
# --- checks
pairs = {}
for ball, (bank, fn, net, vcco) in rows.items():
    m = re.match(r'L(\d+)([PN])_', fn)
    if isdiff(net):
        base = net[:-2]
        pairs.setdefault(base, {})[net[-1]] = (ball, fn, bank)
        if m and m.group(2) != net[-1]:
            issues.append('%s on %s (%s): pin polarity is %s' % (net, ball, fn, m.group(2)))
for base, pr in pairs.items():
    if len(pr) == 2:
        mp = re.match(r'L(\d+)', pr['P'][1])
        mn = re.match(r'L(\d+)', pr['N'][1])
        if not (mp and mn and mp.group(1) == mn.group(1) and pr['P'][2] == pr['N'][2]):
            issues.append('%s: P on %s/%s, N on %s/%s are not one differential pair' % (base, pr['P'][0], pr['P'][1], pr['N'][0], pr['N'][1]))
clocks = {'SYSCLK_100M', 'FMC_CLK'} | {r[2] for r in rows.values() if r[2].startswith('MEZZ_CLK') or '_CC_' in r[2]}
for ball, (bk, fn, n, v) in rows.items():
    if n in clocks and not n.endswith('_N') and 'MRCC' not in fn and 'SRCC' not in fn:
        issues.append('%s on %s (%s) is not a clock-capable pin' % (n, ball, fn))
for c in ('SYSCLK_100M', 'FMC_CLK'):
    if not any(r[2] == c for r in rows.values()):
        notes.append('%s is not on a bank IO pin in pinout.md' % c)
# ddr byte groups
tg = lambda fn: (re.search(r'_T(\d)', fn) or [None, None])[1]
for lane, nets in ((0, ['DDR_DQ%d' % i for i in range(8)] + ['DDR_DM0']), (1, ['DDR_DQ%d' % i for i in range(8, 16)] + ['DDR_DM1'])):
    dqs = [(ball, fn) for ball, (bk, fn, n, v) in rows.items() if n in ('DDR_DQS%d_P' % lane, 'DDR_DQS%d_N' % lane)]
    if not all('DQS' in fn for _, fn in dqs) or len(dqs) != 2:
        issues.append('DDR_DQS%d is not on the DQS pins of a byte group: %s' % (lane, dqs))
    t = {tg(fn) for _, fn in dqs}
    for n in nets:
        hit = [(ball, fn) for ball, (bk, fn, nn, v) in rows.items() if nn == n]
        if hit and tg(hit[0][1]) not in t:
            issues.append('%s on %s (%s) is outside DQS%d byte group T%s' % (n, hit[0][0], hit[0][1], lane, ','.join(sorted(t))))
vref = [(ball, fn, n) for ball, (bk, fn, n, v) in rows.items() if bk == '34' and 'VREF' in fn and n not in ('NC', '')]
if vref:
    notes.append('bank 34 uses its VREF pins as IO (%s): internal VREF is required' % ', '.join('%s=%s' % (b_, n) for b_, f, n in vref))
    lines.append('set_property INTERNAL_VREF 0.675 [get_iobanks 34]')
for bank in by_bank:
    v = by_bank[bank][0][3]
    for net, ball, fn, vcco in by_bank[bank]:
        s = iostd(bank, net, vcco)
        if s is None:
            issues.append('bank %s (VCCO %s): no IO standard for %s' % (bank, vcco, net))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote %s: %d pins in %d banks, %d transceiver pins' % (OUT, len(rows), len(by_bank), len(gtp)))
print('issues (%d):' % len(issues))
for i in issues:
    print('  ' + i)
for n in notes:
    print('note: ' + n)
